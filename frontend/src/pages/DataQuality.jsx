import { useEffect, useState } from "react";
import { RefreshCw, ShieldCheck, ShieldAlert } from "lucide-react";
import { getDataQualitySummary } from "../services/dataQualityService";
import "./DataQuality.css";

function getErrorMessage(err, fallback) {
  if (!err.response) {
    return "Cannot reach the backend. Make sure uvicorn is running.";
  }
  return err.response.data?.detail || err.message || fallback;
}

function formatKey(key) {
  return key.replaceAll("_", " ");
}

function formatValue(value) {
  if (typeof value === "boolean") return value ? "Yes" : "No";
  if (typeof value === "number") return value.toLocaleString();
  return String(value ?? "—");
}

function DataQuality() {
  const [data, setData] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");

  const loadData = async () => {
    try {
      setLoading(true);
      setError("");
      setData(await getDataQualitySummary());
    } catch (err) {
      setError(getErrorMessage(err, "Unable to load the data-quality report."));
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    loadData();
  }, []);

  if (loading) {
    return <div className="quality-page">Loading data quality report...</div>;
  }

  if (error) {
    return (
      <div className="quality-page">
        <h1>Data Quality</h1>
        <div className="quality-error">{error}</div>
        <button onClick={loadData}>Retry</button>
      </div>
    );
  }

  const totalErrors = data.reports.reduce(
    (sum, item) => sum + Number(item.error_count), 0
  );
  const totalWarnings = data.reports.reduce(
    (sum, item) => sum + Number(item.warning_count), 0
  );
  const totalIssues = data.reports.reduce(
    (sum, item) => sum + item.total_issues, 0
  );

  return (
    <div className="quality-page">
      <div className="quality-header">
        <div>
          <p className="quality-eyebrow">DATA GOVERNANCE</p>
          <h1>Data Quality Dashboard</h1>
          <p>Saved validation results for the synthetic dataset and support assessments.</p>
        </div>

        <button onClick={loadData}>
          <RefreshCw size={15} />
          Refresh Report
        </button>
      </div>

      <div className="quality-status">
        <span className={data.passed ? "quality-indicator passed" : "quality-indicator failed"}>
          {data.passed ? <ShieldCheck size={15} /> : <ShieldAlert size={15} />}
          {data.passed ? "ALL VALIDATIONS PASSED" : "VALIDATION NEEDS ATTENTION"}
        </span>
        <p>
          Combined status of {data.reports.length} saved validation reports.
        </p>
      </div>

      <div className="quality-cards">
        <div className="quality-card">
          <span>Validation errors</span>
          <strong>{totalErrors}</strong>
        </div>
        <div className="quality-card">
          <span>Warnings</span>
          <strong>{totalWarnings}</strong>
        </div>
        <div className="quality-card">
          <span>Recorded issues</span>
          <strong>{totalIssues}</strong>
        </div>
        <div className="quality-card">
          <span>Labelled edge cases</span>
          <strong>{data.edge_cases.length}</strong>
        </div>
      </div>

      {data.reports.map((item) => (
        <ReportSection key={item.key} item={item} />
      ))}

      <section className="quality-section">
        <h2>Labelled Edge Cases</h2>
        <p className="quality-note">
          Isolated test fixtures kept out of the clean analytics dataset. Each
          one must be caught by validation.
        </p>

        <div className="edge-grid">
          {data.edge_cases.map((edge) => (
            <div className="edge-card" key={edge.case_id}>
              <div className="edge-title">
                <span>{edge.case_id}</span>
                <strong>{formatKey(edge.label).toLowerCase()}</strong>
              </div>
              <p>{edge.description}</p>
              <pre>{JSON.stringify(edge.record, null, 2)}</pre>
            </div>
          ))}
        </div>
      </section>

      <p className="quality-disclaimer">
        This page displays the latest saved validation reports. It does not
        rerun validation; regenerate the reports after changing the data.
      </p>
    </div>
  );
}

function ReportSection({ item }) {
  const { report } = item;

  // Show scalar values as tiles; lists and objects get their own blocks.
  const entries = Object.entries(report).filter(
    ([, value]) => typeof value !== "object" || value === null
  );

  return (
    <section className="quality-section">
      <div className="quality-section-heading">
        <div>
          <h2>{item.title}</h2>
          <span className="quality-note">Generated by {item.script}</span>
        </div>
        <span className={item.passed ? "quality-indicator passed" : "quality-indicator failed"}>
          {item.passed ? "PASSED" : "FAILED"}
        </span>
      </div>

      <div className="report-grid">
        {entries.map(([key, value]) => (
          <div className="report-item" key={key}>
            <span>{formatKey(key)}</span>
            <strong>{formatValue(value)}</strong>
          </div>
        ))}
      </div>

      {report.priority_distribution && (
        <>
          <h3>Priority distribution</h3>
          <div className="report-grid">
            {Object.entries(report.priority_distribution).map(([key, value]) => (
              <div className="report-item" key={key}>
                <span>{key.toLowerCase()}</span>
                <strong>{formatValue(value)}</strong>
              </div>
            ))}
          </div>
        </>
      )}

      {report.checks?.length > 0 && (
        <>
          <h3>Checks run</h3>
          <ul className="check-list">
            {report.checks.map((check) => (
              <li key={check}>{formatKey(check)}</li>
            ))}
          </ul>
        </>
      )}

      <h3>Recorded issues</h3>
      {!item.issues_file_available ? (
        <div className="quality-error">Issues file not found.</div>
      ) : item.issues.length ? (
        <div className="quality-table-wrapper">
          <table>
            <thead>
              <tr>
                {Object.keys(item.issues[0]).map((key) => (
                  <th key={key}>{formatKey(key)}</th>
                ))}
              </tr>
            </thead>
            <tbody>
              {item.issues.map((issue, index) => (
                <tr key={index}>
                  {Object.values(issue).map((value, cellIndex) => (
                    <td key={cellIndex}>{String(value ?? "")}</td>
                  ))}
                </tr>
              ))}
            </tbody>
          </table>
          {item.total_issues > item.issues.length && (
            <p className="quality-note">
              Showing the first {item.issues.length} of {item.total_issues} issues.
            </p>
          )}
        </div>
      ) : (
        <div className="quality-clean">No issues recorded.</div>
      )}
    </section>
  );
}

export default DataQuality;
